<?php

declare(strict_types=1);

namespace App\Repository;

use App\Model\Comment;

/**
 * Data access for the `comments` table, with PDO and prepared statements only.
 * product_id is the product id of the external API (no foreign key).
 *
 * Every read and write is scoped to a product: a comment can only be
 * read, updated or deleted through the product it belongs to.
 */
final class CommentRepository
{
    private const COLUMNS = 'id, product_id, author, content, created_at, updated_at';

    public function __construct(
        private readonly \PDO $pdo,
    ) {
    }

    /**
     * @return list<Comment> most recent first
     */
    public function findByProduct(int $productId): array
    {
        $statement = $this->pdo->prepare(
            'SELECT '.self::COLUMNS.'
             FROM comments
             WHERE product_id = :product_id
             ORDER BY created_at DESC, id DESC'
        );
        $statement->bindValue('product_id', $productId, \PDO::PARAM_INT);
        $statement->execute();

        return array_map(Comment::fromRow(...), $statement->fetchAll(\PDO::FETCH_ASSOC));
    }

    public function findOneForProduct(int $id, int $productId): ?Comment
    {
        $statement = $this->pdo->prepare(
            'SELECT '.self::COLUMNS.'
             FROM comments
             WHERE id = :id AND product_id = :product_id'
        );
        $statement->bindValue('id', $id, \PDO::PARAM_INT);
        $statement->bindValue('product_id', $productId, \PDO::PARAM_INT);
        $statement->execute();

        $row = $statement->fetch(\PDO::FETCH_ASSOC);

        return false === $row ? null : Comment::fromRow($row);
    }

    public function add(int $productId, string $author, string $content): Comment
    {
        $statement = $this->pdo->prepare(
            'INSERT INTO comments (product_id, author, content)
             VALUES (:product_id, :author, :content)'
        );
        $statement->bindValue('product_id', $productId, \PDO::PARAM_INT);
        $statement->bindValue('author', $author);
        $statement->bindValue('content', $content);
        $statement->execute();

        $id = (int) $this->pdo->lastInsertId();

        // Re-read the row to get the dates generated by MySQL
        return $this->findOneForProduct($id, $productId)
            ?? throw new \LogicException(sprintf('Comment %d not found right after insert.', $id));
    }

    /**
     * Returns the updated comment, or null when it does not exist for this product.
     */
    public function update(int $id, int $productId, string $author, string $content): ?Comment
    {
        $statement = $this->pdo->prepare(
            'UPDATE comments
             SET author = :author, content = :content
             WHERE id = :id AND product_id = :product_id'
        );
        $statement->bindValue('author', $author);
        $statement->bindValue('content', $content);
        $statement->bindValue('id', $id, \PDO::PARAM_INT);
        $statement->bindValue('product_id', $productId, \PDO::PARAM_INT);
        $statement->execute();

        // rowCount() is 0 with MySQL when the values did not change,
        // so the existence check is done by reading the row again.
        return $this->findOneForProduct($id, $productId);
    }

    /**
     * Returns false when the comment does not exist for this product.
     */
    public function delete(int $id, int $productId): bool
    {
        $statement = $this->pdo->prepare(
            'DELETE FROM comments
             WHERE id = :id AND product_id = :product_id'
        );
        $statement->bindValue('id', $id, \PDO::PARAM_INT);
        $statement->bindValue('product_id', $productId, \PDO::PARAM_INT);
        $statement->execute();

        return $statement->rowCount() > 0;
    }
}